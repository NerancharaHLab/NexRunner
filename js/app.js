function loadRunHistoryJSON(event) {
    let file = event.target.files[0];
    if (!file) return;

    let reader = new FileReader();
    reader.onload = function(e) {
        try {
            let data = JSON.parse(e.target.result);
            if (!Array.isArray(data.runs)) {
                alert('รูปแบบไฟล์ JSON ไม่ถูกต้องสำหรับประวัติการ Run');
                return;
            }
            let { added, updated, renumbered } = mergeRunHistory(data.runs);
            let msg = `รวมประวัติ Run สำเร็จ: เพิ่ม ${added}, อัปเดต ${updated}`;
            if (renumbered > 0) msg += `, แก้เลขชนกัน ${renumbered} รายการ (เก็บข้อมูลไว้ครบ ไม่มีลบทิ้ง)`;
            showToast(msg);
        } catch (err) {
            console.error('Failed to parse run history file', err);
            alert('ไม่สามารถอ่านไฟล์ JSON ประวัติการ Run ได้');
        }
    };
    reader.readAsText(file);
    event.target.value = '';
}

