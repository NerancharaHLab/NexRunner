function handleEvidenceFiles(scId, fileList) {
    Array.from(fileList || []).forEach(file => {
        if (file.type && file.type.startsWith('image/')) {
            processEvidenceBlob(scId, file);
        }
    });
    let cleanId = scId.replace(/[^a-zA-Z0-9]/g, '');
    let input = document.getElementById('evidence-file-' + cleanId);
    if (input) input.value = '';
}

function handleEvidencePaste(event, scId) {
    let clipboard = event.clipboardData || window.clipboardData;
    if (!clipboard || !clipboard.items) return;
    let found = false;
    for (let i = 0; i < clipboard.items.length; i++) {
        let item = clipboard.items[i];
        if (item.type && item.type.startsWith('image/')) {
            let blob = item.getAsFile();
            if (blob) {
                processEvidenceBlob(scId, blob);
                found = true;
            }
        }
    }
    if (found) event.preventDefault();
}

function processEvidenceBlob(scId, blob) {
    let reader = new FileReader();
    reader.onload = function(e) {
        let img = new Image();
        img.onload = function() {
            let w = img.width, h = img.height;
            if (w > EVIDENCE_MAX_DIM || h > EVIDENCE_MAX_DIM) {
                if (w >= h) { h = Math.round(h * (EVIDENCE_MAX_DIM / w)); w = EVIDENCE_MAX_DIM; }
                else { w = Math.round(w * (EVIDENCE_MAX_DIM / h)); h = EVIDENCE_MAX_DIM; }
            }
            let canvas = document.createElement('canvas');
            canvas.width = w;
            canvas.height = h;
            canvas.getContext('2d').drawImage(img, 0, 0, w, h);
            let dataUrl = canvas.toDataURL('image/jpeg', EVIDENCE_JPEG_QUALITY);
            addEvidenceImage(scId, dataUrl);
        };
        img.onerror = function() {
            showToast('ไม่สามารถอ่านรูปภาพนี้ได้');
        };
        img.src = e.target.result;
    };
    reader.readAsDataURL(blob);
}

function addEvidenceImage(scId, dataUrl) {
    if (!testState.scenarios) testState.scenarios = {};
    let siteKey = currentSiteKey || 'NUH';
    if (!testState.scenarios[siteKey]) testState.scenarios[siteKey] = {};
    if (!testState.scenarios[siteKey][scId]) testState.scenarios[siteKey][scId] = { status: 'notrun', notes: '' };
    let stateObj = testState.scenarios[siteKey][scId];
    if (!stateObj.evidence) stateObj.evidence = [];

    if (stateObj.evidence.length >= EVIDENCE_MAX_PER_SCENARIO) {
        showToast(`แนบได้สูงสุด ${EVIDENCE_MAX_PER_SCENARIO} รูปต่อ Scenario`);
        return;
    }

    stateObj.evidence.push({
        id: 'ev-' + Date.now() + '-' + Math.random().toString(36).slice(2, 7),
        dataUrl: dataUrl,
        addedAt: new Date().toISOString()
    });

    try {
        saveState();
    } catch (err) {
        stateObj.evidence.pop();
        showToast('พื้นที่จัดเก็บเต็ม ลบรูปเก่าออกก่อนแนบเพิ่ม');
        console.error('Evidence save failed', err);
        return;
    }

    renderEvidenceThumbs(scId);
}

function removeEvidence(scId, evidenceId) {
    let siteKey = currentSiteKey || 'NUH';
    let stateObj = testState.scenarios && testState.scenarios[siteKey] && testState.scenarios[siteKey][scId];
    if (!stateObj || !stateObj.evidence) return;
    stateObj.evidence = stateObj.evidence.filter(ev => ev.id !== evidenceId);
    saveState();
    renderEvidenceThumbs(scId);
}

