function renderRunHistoryTable() {
    let tbody = document.getElementById('run-history-tbody');
    if (!tbody) return;

    if (!runHistory.length) {
        tbody.innerHTML = `<tr><td colspan="12" style="text-align:center; color: var(--text-secondary); padding: 16px;">ยังไม่มีประวัติการ Run — กด "โหลดประวัติ" เพื่อนำเข้าไฟล์ที่แชร์ไว้</td></tr>`;
        return;
    }

    let sorted = [...runHistory].sort((a, b) => {
        if (a.siteKey !== b.siteKey) return a.siteKey.localeCompare(b.siteKey);
        return (b.runNumber || 0) - (a.runNumber || 0);
    });

    tbody.innerHTML = sorted.map(r => {
        let m = r.metrics || {};
        let badgeClass = r.gateResult === 'READY' ? 'badge-ready' : 'badge-notready';
        return `
            <tr>
                <td><strong>${r.siteKey}</strong></td>
                <td>${r.runNumber}</td>
                <td>${r.runId}</td>
                <td>${r.environment}</td>
                <td>${r.executedDate}</td>
                <td>${r.tester || '-'}</td>
                <td>${m.passed ?? '-'}</td>
                <td>${m.failed ?? '-'}</td>
                <td>${m.blocked ?? '-'}</td>
                <td>${m.notrun ?? '-'}</td>
                <td>${m.passRatePercent ?? '-'}%</td>
                <td style="text-align:center;"><span class="status-badge ${badgeClass}">${r.gateResult}</span></td>
            </tr>
        `;
    }).join('');
}

/* Test Execution Result Save & Load Logic */
function saveTestResultJSON() {
    saveMetadata();
    
    let m = testState.metadata || {};
    let siteKey = currentSiteKey || 'NUH';
    let siteScenariosState = (testState.scenarios && testState.scenarios[siteKey]) ? testState.scenarios[siteKey] : {};
    
    let p = 0, f = 0, b = 0, nr = 0;
    activeScenarios.forEach(sc => {
        let st = (siteScenariosState[sc.id] && siteScenariosState[sc.id].status) ? siteScenariosState[sc.id].status : 'notrun';
        if (st === 'passed') p++;
        else if (st === 'failed') f++;
        else if (st === 'blocked') b++;
        else nr++;
    });

    let total = activeScenarios.length || 17;
    let rate = Math.round((p / total) * 100);

    let resultPayload = {
        app: "Smoke Test Runner & Report Generator",
        formatVersion: "1.0",
        savedAt: new Date().toISOString(),
        siteKey: siteKey,
        siteName: m.site || siteKey,
        environment: m.env || 'STAGING',
        runId: m.runid || 'SM-RUN-001',
        testCycle: m.cycle || 'Cycle 1',
        executedDate: m.date || new Date().toISOString().split('T')[0],
        tester: m.tester || '',
        dataChain: {
            version: m.ver || '',
            deliveryBatch: m.delivery || '',
            hn: m.hn || '',
            vn: m.vn || '',
            an: m.an || '',
            bill: m.bill || ''
        },
        metrics: {
            totalScenarios: total,
            passed: p,
            failed: f,
            blocked: b,
            notrun: nr,
            passRatePercent: rate,
            criticalPass: activeScenarios.filter(s => s.critical).every(s => siteScenariosState[s.id] && siteScenariosState[s.id].status === 'passed')
        },
        metadata: m,
        scenariosResult: siteScenariosState
    };

    let gateResult = (resultPayload.metrics.criticalPass && f === 0 && b === 0 && activeScenarios.length > 0) ? 'READY' : 'NOT READY';

    let jsonStr = JSON.stringify(resultPayload, null, 2);
    let blob = new Blob([jsonStr], { type: 'application/json' });
    let url = URL.createObjectURL(blob);

    let cleanRunId = (m.runid || 'RUN').replace(/[^a-zA-Z0-9_-]/g, '');
    let cleanDate = (m.date || new Date().toISOString().split('T')[0]).replace(/[^a-zA-Z0-9_-]/g, '');
    let fileName = `test_result_${siteKey}_${cleanRunId}_${cleanDate}.json`;

    let a = document.createElement('a');
    a.href = url;
    a.download = fileName;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    showToast(`บันทึกไฟล์ผลการทดสอบ ${fileName} เรียบร้อยแล้ว!`);
    recordRunToHistory(resultPayload, gateResult, fileName);
}

